"""Quality gate for the sample reports shipped in ui/gallery/ — each one must be a report worth showing.

These files are generated by a live run (scripts/generate_gallery.py), so nothing else in the suite would
notice a bad one.  The batteries report once shipped with every citation written as 【1】 and an empty
reference list; these checks exist so that cannot happen again unnoticed."""
import re

import pytest

from research_analyst.grounding.verify import Claim, support_for
from research_analyst.ui.gallery import GALLERY_DIR, load_gallery
from research_analyst.ui.about import SAMPLE_QUESTIONS

ENTRIES = load_gallery(GALLERY_DIR)


def test_one_report_per_example_question():
    assert {e["question"] for e in ENTRIES} == set(SAMPLE_QUESTIONS)


@pytest.mark.parametrize("entry", ENTRIES, ids=lambda e: e["id"][:40])
class TestEachBundledReport:
    def test_has_the_required_sections_in_order(self, entry):
        headers = re.findall(r"^## (.+)$", entry["report"], flags=re.M)
        want = ["Executive Summary", "Key Findings", "Detailed Analysis", "Contradictions", "Knowledge Gaps", "References"]
        positions = [next(i for i, h in enumerate(headers) if w.lower() in h.lower()) for w in want]
        assert positions == sorted(positions)

    def test_citations_are_ascii_markers_with_a_real_reference_list(self, entry):
        body = entry["report"].split("## References")[0]
        assert "【" not in body and "】" not in body, "citation brackets must be normalised to [n]"
        markers = {int(n) for n in re.findall(r"\[(\d+)\]", body)}
        assert len(markers) >= 3 and entry["references"]
        assert markers <= {r["n"] for r in entry["references"]}, "every [n] in the text must resolve to a reference"
        for r in entry["references"]:
            assert r["url"].startswith("http") and f"[{r['n']}]" in entry["report"].split("## References")[-1]

    def test_no_internal_markers_or_html_leak_into_the_report(self, entry):
        assert not re.search(r"\[S:[0-9a-f]{6}\]|\[F\d+\]|<script|<img|!\[", entry["report"])

    def test_every_claim_resolves_to_evidence_the_verify_panel_can_show(self, entry):
        v = entry["verify"]
        assert len(v["claims"]) >= 5
        for c in v["claims"]:
            for s in support_for(Claim(c["id"], c["text"], tuple(c["refs"])), v["evidence"]):
                assert s["url"], f"claim {c['id']} cites a source with no evidence entry"

    def test_cost_and_provenance_are_recorded(self, entry):
        assert entry["usage"]["total_tokens"] and entry["usage"]["calls"] and entry["seconds"] > 0
        assert entry["models"].get("strong") and entry["generated_at"]
